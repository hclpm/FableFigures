#!/usr/bin/env node
"use strict";

/* Rebuild Human > Anatomy as detailed split-body medical illustrations. */
const fs=require("fs"),path=require("path");
const root=path.resolve(__dirname,"..");
const outDir=path.join(root,"app","assets","human","anatomy");
const rasterDir=path.join(outDir,"raster");
const registryFile=path.join(root,"app","human-anatomy-assets.js");
const ids=["anatomy_female","anatomy_male"];
const sizes={anatomy_female:[82,150],anatomy_male:[82,150]};
const viewBoxes={anatomy_female:"0 0 54 100",anatomy_male:"0 0 54 100"};
const files={anatomy_female:"female-anatomy.png",anatomy_male:"male-anatomy.png"};
const metadata={
  anatomy_female:{
    label:"Female anatomy · Half-transparent",
    description:"Full-body anterior female anatomical mannequin divided at the median plane, with an intact external half and a transparent half exposing the brain, skeleton, major muscles, vessels, thoracoabdominal organs, urinary tract, uterus, ovary, and uterine tube.",
    designBasis:"A vertical split preserves the relationship between surface anatomy and internal position while sex-specific pelvic anatomy is shown without labels or explicit external detail."
  },
  anatomy_male:{
    label:"Male anatomy · Half-transparent",
    description:"Full-body anterior male anatomical mannequin divided at the median plane, with an intact external half and a transparent half exposing the brain, skeleton, major muscles, vessels, thoracoabdominal organs, urinary tract, prostate, and simplified internal reproductive tract.",
    designBasis:"The shared pose and split direction support direct comparison with the female figure while retaining male pelvic anatomy and neutral publication-oriented presentation."
  }
};

const icons={};
for(const id of ids){
  const rasterPath=path.join(rasterDir,files[id]);
  if(!fs.existsSync(rasterPath)) throw new Error(`Missing anatomy raster: ${rasterPath}`);
  const raster=fs.readFileSync(rasterPath).toString("base64");
  icons[id]=`<image x="0" y="0" width="54" height="100" preserveAspectRatio="xMidYMid meet" href="data:image/png;base64,${raster}"/>`;
}

const esc=s=>String(s).replace(/[&<>]/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;"}[c]));
fs.mkdirSync(outDir,{recursive:true});

const manifest={version:1,generated:"2026-08-05",style:"detailed matte split-body medical illustration",icons:[]};
for(const id of ids){
  const m=metadata[id];
  const svg=`<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBoxes[id]}" role="img" aria-labelledby="title desc">\n  <title id="title">${esc(m.label)}</title>\n  <desc id="desc">${esc(m.description)} Design basis: ${esc(m.designBasis)}</desc>\n  <metadata>${esc(JSON.stringify({id,label:m.label,description:m.description,designBasis:m.designBasis}))}</metadata>\n  ${icons[id]}\n</svg>\n`;
  fs.writeFileSync(path.join(outDir,id+".svg"),svg);
  manifest.icons.push({id,label:m.label,file:id+".svg",size:sizes[id],description:m.description,designBasis:m.designBasis});
}

fs.writeFileSync(path.join(outDir,"manifest.json"),JSON.stringify(manifest,null,2)+"\n");
fs.writeFileSync(path.join(outDir,"README.md"),`# Human · Anatomy assets\n\nTwo full-body anterior anatomical figures with an intact external half and a transparent internal half. Transparent PNG layers are embedded in standalone SVG wrappers and registered by \`scripts/rebuild-human-anatomy-assets.js\`.\n`);

const registry=`/* Generated by scripts/rebuild-human-anatomy-assets.js. */\n(function(global){\n"use strict";\nvar HUMAN_ANATOMY_ICONS=${JSON.stringify(icons,null,2)};\nvar HUMAN_ANATOMY_SIZES=${JSON.stringify(sizes,null,2)};\nvar HUMAN_ANATOMY_VIEWBOXES=${JSON.stringify(viewBoxes,null,2)};\nvar HUMAN_ANATOMY_METADATA=${JSON.stringify(metadata,null,2)};\nObject.keys(HUMAN_ANATOMY_ICONS).forEach(function(id){global.CAM.ICONS[id]=HUMAN_ANATOMY_ICONS[id];global.CAM.ICON_SIZES[id]=HUMAN_ANATOMY_SIZES[id];global.CAM.ICON_VIEWBOXES[id]=HUMAN_ANATOMY_VIEWBOXES[id];});\nglobal.CAM.HUMAN_ANATOMY_METADATA=HUMAN_ANATOMY_METADATA;\nglobal.CAM.HUMAN_ANATOMY_ICON_SOURCE="app/assets/human/anatomy";\n})(window);\n`;
fs.writeFileSync(registryFile,registry);
console.log(`Generated ${ids.length} Human > Anatomy SVGs in ${outDir}`);
